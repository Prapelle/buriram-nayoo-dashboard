# สร้างไฟล์ทดสอบจำลอง (ไม่ใช่ข้อมูลจริง) ให้มีโครงสร้างตามสเปก: หัวบริษัท/ช่วงรายงานด้านบน, หัวตารางแถวที่ 6, วันที่เป็น Excel serial,
# จำนวนเงินบางช่องเป็นข้อความมีคอมมา, แถวว่าง, แถวสรุป "ยอดรวมทั้งหมด"  ใช้: python3 tests/make-sales-fixture.py out.xlsx
import sys, datetime
from openpyxl import Workbook

HEAD = ["วัน/เดือน/ปี","เลขที่เอกสาร","ชื่อลูกค้า","ชื่อโปรเจ็ค","เลขผู้เสียภาษี","สำนักงานใหญ่/สาขา","ขายแยกภาษี","ขายรวมภาษี","ส่วนลดก่อน VAT","ส่วนลดตามเอกสาร","มูลค่า","ภาษีมูลค่าเพิ่ม","ยอดรวมสุทธิ","เอกสารอ้างอิงในระบบ","เลขที่อ้างอิง","เอกสารอ้างอิงรับมัดจำ","สถานะ","พนักงานขาย","หมายเหตุ","โน้ต (สำหรับใช้ภายในบริษัท)"]
A, B, C = "ชนิกานต์ มณีวรรณ", "Suparkit Jaturapatpaibul", "บุรีรัมย์น่าอยู่"
# (gross, discount, salesperson, discount-in-doc-column?)
DOCS = [(80000,10000,A),(40000,5000,A),(25000,5000,A),(20000,0,B),(10000,5000,B),
        (5000,3000,C),(4000,2000,C),(3576,1000,C),(3000,1000,C),(3000,1000,C),(3000,1000,C),(3000,1000,C)]
CUST = ["ลูกค้า ก","ลูกค้า ข","ลูกค้า ค","ลูกค้า ง","ลูกค้า จ","ลูกค้า ฉ","ลูกค้า ช","ลูกค้า ซ","ลูกค้า ฌ","ลูกค้า ญ","ลูกค้า ก","ลูกค้า ฎ"]  # ก ซ้ำ 1 ครั้ง -> 11 ราย
CID = {c: i + 10 for i, c in enumerate(dict.fromkeys(CUST))}  # ลูกค้าเดียวกัน = เลขผู้เสียภาษีเดียวกัน
out = sys.argv[1] if len(sys.argv) > 1 else "synthetic_SalesReport.xlsx"
wb = Workbook(); ws = wb.active; ws.title = "SalesReport"
ws["A1"] = "บริษัท ทดสอบ ดิจิตอล จำกัด"
ws["A2"] = "เลขประจำตัวผู้เสียภาษี 0105551234567"
ws["A3"] = "รายงานยอดขาย"
ws["A4"] = "ระหว่างวันที่ 01/09/2026 ถึง 30/09/2026"
for i, h in enumerate(HEAD, 1): ws.cell(6, i, h)
r = 7
for n, (g, d, sp) in enumerate(DOCS):
    net = g - d
    ws.cell(r, 1, datetime.date(2026, 9, 1 + n * 2))
    ws.cell(r, 2, f"IV2609-{n+1:04d}"); ws.cell(r, 3, CUST[n]); ws.cell(r, 4, f"โปรเจ็ค {n % 3 + 1}")
    ws.cell(r, 5, f"01055{CID[CUST[n]]:08d}"[:13]); ws.cell(r, 6, "สำนักงานใหญ่")
    ws.cell(r, 7, f"{g:,.2f}" if n % 2 else g)            # ข้อความมีคอมมาสลับกับตัวเลข
    ws.cell(r, 8, g)
    ws.cell(r, 9, d if d else None)
    ws.cell(r, 10, None if n == 8 else (d if d else None))  # เอกสารที่ 9: ส่วนลดตามเอกสารว่าง ใช้ส่วนลดก่อน VAT แทน
    ws.cell(r, 11, net); ws.cell(r, 12, 0); ws.cell(r, 13, f"{net:,.2f}" if n % 3 == 0 else net)
    ws.cell(r, 17, "เก็บเงินแล้ว"); ws.cell(r, 18, sp)
    r += 1
    if n == 5: r += 1  # แถวว่างกลางตาราง
r += 1
ws.cell(r, 3, "ยอดรวมทั้งหมด")
ws.cell(r, 7, 199576); ws.cell(r, 9, 35000); ws.cell(r, 10, 34000); ws.cell(r, 11, 164576); ws.cell(r, 12, 0); ws.cell(r, 13, 164576)
wb.save(out)
